import math

COMPONENTS = ("H2", "N2", "CO", "CO2", "CH4", "C2H6", "C3H8", "C4H10", "C5H12", "C6H14")
FEED_NAMES = ("Chemical feed gas", "Natural gas", "Hydrogenation gas")
MOLAR_VOLUME = 8.31446261815324 * 288.15 / 101.325
PROFILES = (
    dict(toCO=1198.24796 / 2799.342, toCO2=860.32926 / 2799.342,
         shift=(1198.24796 - 302.46683) / 1198.24796, recovery=0.9),
    dict(toCO=1157.1522822335025 / 2710.805782571912,
         toCO2=856.8985731810491 / 2710.805782571912,
         shift=(0.123 - 0.0282) / (0.123 * (1 + 0.0282)), recovery=0.9),
    dict(toCO=1184.917011989101 / 2776.5916331258095,
         toCO2=844.5407485388594 / 2776.5916331258095,
         shift=(1187.8776 - 299.3699) / 1187.8776, recovery=0.9),
)
SETTING_LABELS = {
    "toCO": "Reformer carbon converted to CO (%)",
    "toCO2": "Reformer carbon converted to CO2 (%)",
    "shift": "Shift CO conversion (%)",
    "recovery": "PSA hydrogen recovery (%)",
}
RESULTS = (
    ("H2 entering with feed (kmol/h)", "inletH2", 1),
    ("H2 generated by reactions (kmol/h)", "generatedH2", 1),
    ("H2 before PSA (kmol/h)", "beforePSA", 1),
    ("H2 product after PSA (kmol/h)", "productH2", 1),
    ("CO2 generated (t/h)", "generatedCO2", 0.044),
    ("Total process CO2 (t/h)", "totalCO2", 0.044),
    ("Reaction water consumed (t/h)", "water", 0.018),
    ("CO remaining after shift (kmol/h)", "remainingCO", 1),
)


def feed_preset(case):
    if case not in ("A", "B"):
        raise ValueError("Select Feed Case A or B.")
    return [
        dict(flow=16173 if case == "A" else 0,
             composition=[18.28, 0, 0, 0, 41.97, 19.17, 11.91, 6.72, 1.94, 0]),
        dict(flow=40403 if case == "A" else 62424,
             composition=[0, 1.6, 0, 0.69, 93.875, 2.88, 0.75, 0.18, 0.02, 0.005]),
        dict(flow=0 if case == "A" else 1931,
             composition=[96, 0, 0, 0, 4, 0, 0, 0, 0, 0]),
    ]


def finite_number(value):
    return type(value) in (int, float) and math.isfinite(value)


def calculate(scenario):
    if not isinstance(scenario, dict):
        raise ValueError("Scenario is incomplete.")
    settings, feeds = scenario.get("settings"), scenario.get("feeds")
    if (scenario.get("feedCase") not in ("A", "B")
            or type(scenario.get("profile")) is not int
            or scenario["profile"] not in range(3)
            or not isinstance(settings, dict)
            or not isinstance(feeds, list) or len(feeds) != 3):
        raise ValueError("Scenario is incomplete. Restore a preset.")
    for key in SETTING_LABELS:
        value = settings.get(key)
        if not finite_number(value) or not 0 <= value <= 1:
            raise ValueError("Conversion and recovery must be between 0 and 100%.")
    a, b, shift, recovery = (settings[k] for k in SETTING_LABELS)
    if a + b > 1:
        raise ValueError("Reformer CO and CO2 conversion must total no more than 100%.")
    rows = []
    for name, feed in zip(FEED_NAMES, feeds):
        if not isinstance(feed, dict) or not finite_number(feed.get("flow")) or feed["flow"] < 0:
            raise ValueError(f"{name} flow must be a finite, nonnegative number.")
        composition = feed.get("composition")
        if (not isinstance(composition, list) or len(composition) != 10
                or any(not finite_number(v) or not 0 <= v <= 100 for v in composition)):
            raise ValueError(f"{name} composition requires ten values between 0 and 100%.")
        total = sum(composition)
        if abs(total - 100) > 0.02 + 1e-10:
            raise ValueError(f"{name} composition must total 100% (rounding allowance +/-0.02 percentage points).")
        inlet = [feed["flow"] / MOLAR_VOLUME * x / total for x in composition]
        reformer = inlet.copy()
        water = 0.0
        for i in range(4, 10):
            n, mol = i - 3, inlet[i]
            reformer[i] = mol * (1 - a - b)
            reformer[0] += mol * ((2 * n + 1) * a + (3 * n + 1) * b)
            reformer[2] += mol * n * a
            reformer[3] += mol * n * b
            water += mol * n * (a + 2 * b)
        converted = reformer[2] * shift
        outlet = reformer.copy()
        outlet[0] += converted
        outlet[2] -= converted
        outlet[3] += converted
        rows.append(dict(
            inlet=inlet, reformer=reformer, outlet=outlet,
            inletH2=inlet[0], generatedH2=outlet[0] - inlet[0],
            beforePSA=outlet[0], productH2=outlet[0] * recovery,
            generatedCO2=outlet[3] - inlet[3], totalCO2=outlet[3],
            water=water + converted, remainingCO=outlet[2],
        ))
    totals = {key: sum(row[key] for row in rows) for _, key, _ in RESULTS}
    if (any(not math.isfinite(v) for v in totals.values())
            or not math.isfinite(totals["productH2"] * MOLAR_VOLUME)):
        raise ValueError("Inputs exceed the supported calculation range. Reduce the feed flow.")
    return dict(feeds=rows, totals=totals)


class Calculator:
    def __init__(self, root):
        import tkinter as tk
        from tkinter import ttk

        self.root = root
        self.busy = True
        self.case = tk.StringVar(root, "A")
        self.profile = tk.StringVar(root, "1")
        self.status = tk.StringVar(root)
        self.feed_vars = [[tk.StringVar(root) for _ in range(11)] for _ in FEED_NAMES]
        self.setting_vars = {key: tk.StringVar(root) for key in SETTING_LABELS}
        self.headlines = [tk.StringVar(root) for _ in range(3)]
        self.composition_totals = [tk.StringVar(root) for _ in FEED_NAMES]
        self.result = None
        root.title("Hydrogen Production")
        root.geometry("1040x710")
        root.minsize(900, 650)
        frame = ttk.Frame(root, padding=16)
        frame.pack(fill="both", expand=True)
        ttk.Label(frame, text="Hydrogen Production", font=("Segoe UI", 18, "bold")).pack(anchor="w")
        ttk.Label(frame, text="Change a feed or setting to update results automatically.").pack(anchor="w", pady=(4, 12))
        controls = ttk.Frame(frame)
        controls.pack(fill="x")
        for column, (label, variable, values, command) in enumerate((
            ("Feed case", self.case, ("A", "B"), self.restore_feeds),
            ("Conversion dataset", self.profile, ("1", "2", "3"), self.restore_profile),
        )):
            ttk.Label(controls, text=label).grid(row=0, column=column * 2, padx=(0, 8))
            box = ttk.Combobox(controls, textvariable=variable, values=values, state="readonly", width=8)
            box.grid(row=0, column=column * 2 + 1, padx=(0, 20))
            box.bind("<<ComboboxSelected>>", lambda event, fn=command: fn())
        ttk.Button(controls, text="Restore feed preset", command=self.restore_feeds).grid(row=0, column=4, padx=6)
        ttk.Button(controls, text="Restore profile", command=self.restore_profile).grid(row=0, column=5, padx=6)
        cards = ttk.Frame(frame)
        cards.pack(fill="x", pady=14)
        for i, label in enumerate(("Hydrogen product after PSA", "CO2 generated", "Reaction water consumption")):
            card = ttk.LabelFrame(cards, text=label, padding=10)
            card.grid(row=0, column=i, sticky="nsew", padx=(0, 8))
            cards.columnconfigure(i, weight=1)
            ttk.Label(card, textvariable=self.headlines[i], font=("Segoe UI", 13), justify="left").pack(anchor="w")
        tabs = ttk.Notebook(frame)
        tabs.pack(fill="both", expand=True)
        feed_tab, settings_tab, result_tab = (ttk.Frame(tabs, padding=12) for _ in range(3))
        for tab, label in ((feed_tab, "Feed inputs"), (settings_tab, "Calculation settings"), (result_tab, "Results by feed")):
            tabs.add(tab, text=label)
        for i, name in enumerate(FEED_NAMES):
            feed_tab.columnconfigure(i + 1, weight=1)
            ttk.Label(feed_tab, text=name).grid(row=0, column=i + 1, pady=(0, 6))
        for j, label in enumerate(("Flow (Sm3/h)",) + tuple(c + " (mol%)" for c in COMPONENTS)):
            ttk.Label(feed_tab, text=label).grid(row=j + 1, column=0, sticky="w", padx=(0, 20))
            for i in range(3):
                ttk.Entry(feed_tab, textvariable=self.feed_vars[i][j], justify="right").grid(row=j + 1, column=i + 1, sticky="ew", padx=6, pady=2)
        ttk.Label(feed_tab, text="Composition total (%)").grid(row=12, column=0, sticky="w")
        for i in range(3):
            ttk.Label(feed_tab, textvariable=self.composition_totals[i]).grid(row=12, column=i + 1, sticky="e", padx=8)
        ttk.Label(feed_tab, text="Composition rounding within +/-0.02 percentage points is normalized to 100%.").grid(row=13, column=0, columnspan=4, sticky="w", pady=(8, 0))
        for j, (key, label) in enumerate(SETTING_LABELS.items()):
            ttk.Label(settings_tab, text=label).grid(row=j, column=0, sticky="w", pady=10, padx=(0, 25))
            ttk.Entry(settings_tab, textvariable=self.setting_vars[key], justify="right").grid(row=j, column=1, pady=10)
        self.table = ttk.Treeview(result_tab, columns=("metric", "chemical", "natural", "hydrogenation", "total"), show="headings", height=8)
        for key, label in zip(self.table["columns"], ("Result",) + FEED_NAMES + ("Total",)):
            self.table.heading(key, text=label)
            self.table.column(key, width=310 if key == "metric" else 145, minwidth=100, anchor="w" if key == "metric" else "e")
        self.table.pack(fill="both", expand=True)
        ttk.Label(result_tab, text="Per-feed product uses a common PSA recovery for the blended feed.").pack(anchor="w", pady=10)
        ttk.Label(frame, textvariable=self.status, wraplength=980).pack(anchor="w", pady=(10, 0))
        self.restore_feeds()
        self.restore_profile()
        for var in [v for feed in self.feed_vars for v in feed] + list(self.setting_vars.values()):
            var.trace_add("write", self.refresh)
        self.busy = False
        self.refresh()

    def restore_feeds(self):
        previous, self.busy = self.busy, True
        for variables, feed in zip(self.feed_vars, feed_preset(self.case.get())):
            for var, value in zip(variables, [feed["flow"]] + feed["composition"]):
                var.set(str(value))
        self.busy = previous
        self.refresh()

    def restore_profile(self):
        previous, self.busy = self.busy, True
        self.base_settings = PROFILES[int(self.profile.get()) - 1].copy()
        self.base_text = {key: f"{value * 100:.6f}" for key, value in self.base_settings.items()}
        for key, var in self.setting_vars.items():
            var.set(self.base_text[key])
        self.busy = previous
        self.refresh()

    def scenario(self):
        return dict(
            feedCase=self.case.get(), profile=int(self.profile.get()) - 1,
            feeds=[dict(flow=float(v[0].get()), composition=[float(x.get()) for x in v[1:]]) for v in self.feed_vars],
            settings={key: self.base_settings[key] if var.get() == self.base_text[key] else float(var.get()) / 100 for key, var in self.setting_vars.items()},
        )

    def refresh(self, *_):
        if self.busy:
            return
        for variables, total in zip(self.feed_vars, self.composition_totals):
            try:
                value = sum(float(v.get()) for v in variables[1:])
                total.set(f"{value:.3f}" if math.isfinite(value) else "Unavailable")
            except ValueError:
                total.set("Unavailable")
        try:
            scenario = self.scenario()
        except ValueError:
            scenario = None
        try:
            if scenario is None:
                raise ValueError("Complete every input with a number to calculate results.")
            self.result = calculate(scenario)
            t = self.result["totals"]
            self.headlines[0].set(f"{t['productH2'] * MOLAR_VOLUME:,.2f} Sm3/h\n{t['productH2']:,.2f} kmol/h")
            self.headlines[1].set(f"{t['generatedCO2'] * 0.044:,.2f} t/h\nTotal process CO2: {t['totalCO2'] * 0.044:,.2f} t/h")
            self.headlines[2].set(f"{t['water'] * 0.018:,.2f} t/h\nReforming and shift")
            self.table.delete(*self.table.get_children())
            for label, key, factor in RESULTS:
                values = [f"{row[key] * factor:,.2f}" for row in self.result["feeds"] + [t]]
                self.table.insert("", "end", values=[label] + values)
            self.status.set("Results updated. Reaction water excludes excess steam; process CO2 excludes combustion.")
        except (ValueError, OverflowError) as error:
            self.result = None
            for var in self.headlines:
                var.set("Unavailable")
            self.table.delete(*self.table.get_children())
            self.status.set(str(error))


if __name__ == "__main__":
    import tkinter as tk
    root = tk.Tk()
    Calculator(root)
    root.mainloop()
