import { useState } from "react";
import {
  calculateHydrogen,
  COMPONENTS,
  COMPONENT_LABELS,
  defaultScenario,
  FEED_NAMES,
  feedPreset,
  MOLAR_VOLUME,
  PROFILES,
  validateScenario,
  type Scenario,
  type Settings,
} from "../engineering/hydrogen";
import { ModelTabs } from "../components/ModelPagePrimitives";
import { DataTable } from "../components/DataTable";
import { HydrogenManual } from "../components/HydrogenManual";
import "./HydrogenProductionPage.css";

const STORAGE = "ferriq.hydrogen.scenario.v1";
function load() {
  try {
    const raw = localStorage.getItem(STORAGE);
    if (!raw) return { scenario: defaultScenario(), notice: "" };
    const data: unknown = JSON.parse(raw);
    validateScenario(data);
    calculateHydrogen(data);
    return { scenario: data, notice: "Saved scenario loaded." };
  } catch {
    return {
      scenario: defaultScenario(),
      notice:
        "Saved scenario could not be loaded. Feed A and Dataset 1 are shown; the stored copy has not been changed.",
    };
  }
}
const fmt = (n: number) =>
  n.toLocaleString("en-CA", { maximumFractionDigits: 2 });
const settingLabels: Record<keyof Settings, string> = {
  toCO: "Reformer carbon converted to CO (%)",
  toCO2: "Reformer carbon converted to CO₂ (%)",
  shift: "Shift CO conversion (%)",
  recovery: "PSA hydrogen recovery (%)",
};

export function HydrogenProductionPage() {
  const [initial] = useState(load);
  const [scenario, setScenario] = useState(initial.scenario);
  const [result, setResult] = useState(() =>
    calculateHydrogen(initial.scenario),
  );
  const [dirty, setDirty] = useState(false);
  const [notice, setNotice] = useState(initial.notice);
  const [tab, setTab] = useState("Overview");
  const [allComponents, setAllComponents] = useState(false);
  let error = "";
  try {
    validateScenario(scenario);
  } catch (e) {
    error = (e as Error).message;
  }
  const edit = (next: Scenario) => {
    setScenario(next);
    setDirty(true);
    setNotice("");
  };
  const run = () => {
    try {
      const next = calculateHydrogen(scenario);
      setResult(next);
      setDirty(false);
      setNotice("Scenario recalculated.");
    } catch (e) {
      setDirty(true);
      setNotice((e as Error).message);
    }
  };
  const save = () => {
    try {
      calculateHydrogen(scenario);
      localStorage.setItem(STORAGE, JSON.stringify(scenario));
      setNotice("Scenario saved in this browser.");
    } catch {
      setNotice(
        "Scenario could not be saved. Check inputs and browser storage access.",
      );
    }
  };
  const preset = feedPreset(scenario.feedCase);
  const customFeed = JSON.stringify(preset) !== JSON.stringify(scenario.feeds);
  const customProfile =
    JSON.stringify(PROFILES[scenario.profile]) !==
    JSON.stringify(scenario.settings);
  const visible = !dirty && !error;
  const total = result.totals;
  const metrics = [
    { label: "H₂ entering with feed (kmol/h)", key: "inletH2", factor: 1 },
    {
      label: "H₂ generated by reactions (kmol/h)",
      key: "generatedH2",
      factor: 1,
    },
    { label: "H₂ before PSA (kmol/h)", key: "beforePSA", factor: 1 },
    { label: "H₂ product after PSA (kmol/h)", key: "productH2", factor: 1 },
    { label: "CO₂ generated (t/h)", key: "generatedCO2", factor: 0.044 },
    { label: "Total process CO₂ (t/h)", key: "totalCO2", factor: 0.044 },
    { label: "Reaction water consumed (t/h)", key: "water", factor: 0.018 },
    {
      label: "CO remaining after shift (kmol/h)",
      key: "remainingCO",
      factor: 1,
    },
  ] as const;
  return (
    <div className="hydrogen-page">
      <h1>Hydrogen Production</h1>
      <p>Steam reforming and hydrogen recovery.</p>
      <span className="hydrogen-mode">Static scenario</span>
      <ModelTabs
        tabs={["Overview", "Engineering manual"]}
        active={tab}
        onChange={setTab}
      />
      {tab === "Engineering manual" ? (
        <HydrogenManual />
      ) : (
        <>
          <div className="hydrogen-controls">
            <label>
              Feed scenario
              <select
                aria-label="Feed scenario"
                value={scenario.feedCase}
                onChange={(e) => {
                  const id = e.target.value as "A" | "B";
                  edit({ ...scenario, feedCase: id, feeds: feedPreset(id) });
                }}
              >
                <option value="A">Case A</option>
                <option value="B">Case B</option>
              </select>
            </label>
            <label>
              Conversion profile
              <select
                aria-label="Conversion profile"
                value={scenario.profile}
                onChange={(e) => {
                  const id = Number(e.target.value);
                  edit({
                    ...scenario,
                    profile: id,
                    settings: { ...PROFILES[id] },
                  });
                }}
              >
                {PROFILES.map((_, i) => (
                  <option key={i} value={i}>
                    Dataset {i + 1}
                  </option>
                ))}
              </select>
            </label>
            <button
              onClick={() =>
                edit({ ...scenario, feeds: feedPreset(scenario.feedCase) })
              }
            >
              Restore feed preset
            </button>
            <button onClick={save} disabled={!!error || dirty}>
              Save scenario
            </button>
            <button className="primary-action" onClick={run} disabled={!!error}>
              Recalculate
            </button>
          </div>
          <p className="hydrogen-state">
            {customFeed ? "Custom feed" : `Feed Case ${scenario.feedCase}`} ·{" "}
            {customProfile
              ? "Custom conversion profile"
              : `Dataset ${scenario.profile + 1}`}
          </p>
          {error && <p role="alert">{error}</p>}
          <p role="status" aria-live="polite">
            {dirty ? "Inputs changed. Recalculate to update results." : notice}
          </p>
          {dirty && notice && <p role="alert">{notice}</p>}
          <div className="hydrogen-results" aria-label="Scenario results">
            <article className="card card-body">
              <h2>Hydrogen product after PSA</h2>
              <div className="hydrogen-value">
                {visible ? fmt(total.productH2 * MOLAR_VOLUME) : "—"}{" "}
                <small>Sm³/h</small>
              </div>
              <p>{visible ? fmt(total.productH2) : "—"} kmol/h</p>
            </article>
            <article className="card card-body">
              <h2>CO₂ generated</h2>
              <div className="hydrogen-value">
                {visible ? fmt(total.generatedCO2 * 0.044) : "—"}{" "}
                <small>t/h</small>
              </div>
              <p>{visible ? fmt(total.generatedCO2) : "—"} kmol/h</p>
              <p>
                Total process CO₂: {visible ? fmt(total.totalCO2 * 0.044) : "—"}{" "}
                t/h
              </p>
            </article>
            <article className="card card-body">
              <h2>Reaction water consumption</h2>
              <div className="hydrogen-value">
                {visible ? fmt(total.water * 0.018) : "—"} <small>t/h</small>
              </div>
              <p>Water consumed by reforming and shift.</p>
            </article>
          </div>
          <ol className="hydrogen-process" aria-label="Process sequence">
            {["Feed blend", "Reformer", "Shift", "PSA"].map((x) => (
              <li key={x}>{x}</li>
            ))}
          </ol>
          <section className="card card-body">
            <h2>Feed inputs</h2>
            <div
              className="table-scroll"
              role="region"
              aria-label="Feed compositions and flows"
              tabIndex={0}
            >
              <table className="data hydrogen-inputs">
                <thead>
                  <tr>
                    <th scope="col">Component</th>
                    {FEED_NAMES.map((name) => (
                      <th scope="col" key={name}>
                        {name}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  <tr>
                    <th scope="row">Flow (Sm³/h)</th>
                    {scenario.feeds.map((f, i) => (
                      <td key={i}>
                        <input
                          type="number"
                          min="0"
                          step="any"
                          aria-label={`${FEED_NAMES[i]} flow (Sm³/h)`}
                          value={Number.isFinite(f.flow) ? f.flow : ""}
                          onChange={(e) =>
                            edit({
                              ...scenario,
                              feeds: scenario.feeds.map((v, j) =>
                                j === i
                                  ? { ...v, flow: e.target.valueAsNumber }
                                  : v,
                              ),
                            })
                          }
                        />
                      </td>
                    ))}
                  </tr>
                  {COMPONENTS.map(
                    (c, k) =>
                      (allComponents || k < 7) && (
                        <tr key={c}>
                          <th scope="row">{COMPONENT_LABELS[k]} (mol%)</th>
                          {scenario.feeds.map((f, i) => (
                            <td key={i}>
                              <input
                                type="number"
                                min="0"
                                max="100"
                                step="any"
                                aria-label={`${FEED_NAMES[i]} ${c} (mol%)`}
                                value={
                                  Number.isFinite(f.composition[k])
                                    ? f.composition[k]
                                    : ""
                                }
                                onChange={(e) =>
                                  edit({
                                    ...scenario,
                                    feeds: scenario.feeds.map((v, j) =>
                                      j === i
                                        ? {
                                            ...v,
                                            composition: v.composition.map(
                                              (x, l) =>
                                                l === k
                                                  ? e.target.valueAsNumber
                                                  : x,
                                            ),
                                          }
                                        : v,
                                    ),
                                  })
                                }
                              />
                            </td>
                          ))}
                        </tr>
                      ),
                  )}
                  <tr>
                    <th scope="row">Composition total</th>
                    {scenario.feeds.map((f, i) => (
                      <td key={i}>
                        {Number.isFinite(
                          f.composition.reduce((a, b) => a + b, 0),
                        )
                          ? fmt(f.composition.reduce((a, b) => a + b, 0))
                          : "—"}
                        %
                      </td>
                    ))}
                  </tr>
                </tbody>
              </table>
            </div>
            <button
              aria-expanded={allComponents}
              onClick={() => setAllComponents(!allComponents)}
            >
              {allComponents ? "Hide" : "Show"} remaining components
            </button>
            <p className="hydrogen-note">
              Composition rounding within ±0.02 percentage points is normalized
              to 100% for calculation.
            </p>
          </section>
          <details className="card card-body">
            <summary>Calculation settings</summary>
            <div className="hydrogen-settings">
              {(Object.keys(settingLabels) as (keyof Settings)[]).map((key) => (
                <label className="editor-field" key={key}>
                  {settingLabels[key]}
                  <input
                    type="number"
                    min="0"
                    max="100"
                    step="any"
                    value={
                      Number.isFinite(scenario.settings[key])
                        ? Number((scenario.settings[key] * 100).toFixed(6))
                        : ""
                    }
                    onChange={(e) =>
                      edit({
                        ...scenario,
                        settings: {
                          ...scenario.settings,
                          [key]: e.target.valueAsNumber / 100,
                        },
                      })
                    }
                  />
                </label>
              ))}
            </div>
            <button
              onClick={() =>
                edit({
                  ...scenario,
                  settings: { ...PROFILES[scenario.profile] },
                })
              }
            >
              Restore profile
            </button>
          </details>
          <details className="card card-body">
            <summary>Results by feed</summary>
            {visible ? (
              <>
                <DataTable
                  caption="Calculated feed contributions"
                  columns={["Result", ...FEED_NAMES, "Total"]}
                  rows={metrics.map((m) => ({
                    Result: m.label,
                    ...Object.fromEntries(
                      result.feeds.map((f, i) => [
                        FEED_NAMES[i],
                        f[m.key] * m.factor,
                      ]),
                    ),
                    Total: total[m.key] * m.factor,
                  }))}
                />
                <p className="hydrogen-note">
                  Per-feed hydrogen product uses the common PSA recovery; the
                  feeds are processed as one blend.
                </p>
              </>
            ) : (
              <p>Recalculate valid inputs to view results.</p>
            )}
          </details>
        </>
      )}
    </div>
  );
}
